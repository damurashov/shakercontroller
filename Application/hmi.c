void hmiInit(void)
{
	HMI_MOTOR_CLK_ENABLE();
	GPIO_InitTypeDef init;

	init.Pin = HMI_MOTOR_LED_PIN;
	init.Mode = GPIO_MODE_OUTPUT_OD;
	init.Pull = GPIO_NOPULL;
	init.Speed = GPIO_SPEED_FREQ_LOW;
	HAL_GPIO_Init(HMI_MOTOR_LED_PORT, &init);
}

void hmiSetMotorLed(int aValue)
{
	if (aValue)
	{
		LL_GPIO_SetOutputPin(HMI_MOTOR_LET_PORT, HMI_MOTOR_LED_PIN);
	}
	else
	{
		LL_GPIO_ResetOutputPin(HMI_MOTOR_LET_PORT, HMI_MOTOR_LED_PIN);
	}
}